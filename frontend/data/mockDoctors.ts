// Precalculated helper for today's relative date slots
const createSlot = (daysOffset: number, hour: number, minute: number): { datetime: string; display: string; daysFromNow: number } => {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  d.setHours(hour, minute, 0, 0);

  let dayLabel = '';
  if (daysOffset === 0) dayLabel = 'Today';
  else if (daysOffset === 1) dayLabel = 'Tomorrow';
  else if (daysOffset === 2) dayLabel = 'In 2 days';
  else if (daysOffset <= 6) {
    const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
    dayLabel = days[d.getDay()];
  } else {
    dayLabel = `In ${daysOffset} days`;
  }

  const timeStr = `${hour.toString().padStart(2, '0')}:${minute.toString().padStart(2, '0')}`;
  return {
    datetime: d.toISOString(),
    display: `${dayLabel} ${timeStr}`,
    daysFromNow: daysOffset,
  };
};

